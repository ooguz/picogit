-- Generates a C file embedding Lua modules.
--   lua embed.lua <bytecode|source> <out.c> <module.lua>...
-- In bytecode mode each module is precompiled and stripped of debug info.
local mode, out = arg[1], arg[2]
assert(mode == "bytecode" or mode == "source", "mode must be bytecode or source")

local f = assert(io.open(out, "wb"))
f:write("/* generated by tools/embed.lua - do not edit */\n#include \"picogit.h\"\n\n")

local names = {}
for i = 3, #arg do
  local path = arg[i]
  local name = path:match("([^/]+)%.lua$")
  local src = assert(io.open(path, "rb")):read("a")
  local data
  if mode == "bytecode" then
    local fn = assert(load(src, "@picogit/" .. name .. ".lua"))
    data = string.dump(fn, true)
  else
    data = src
  end
  local id = #names + 1
  names[id] = name
  f:write(("static const unsigned char mod_%d[%d] = {"):format(id, #data))
  for j = 1, #data do
    if (j - 1) % 20 == 0 then f:write("\n") end
    f:write(data:byte(j), ",")
  end
  f:write("\n};\n")
  names[id] = { name = name, len = #data }
end

f:write("\nconst struct pg_embedded_module pg_embedded_modules[] = {\n")
for id, m in ipairs(names) do
  f:write(('    {"%s", mod_%d, %d},\n'):format(m.name, id, m.len))
end
f:write("    {0, 0, 0}\n};\n")
f:close()
