#!/usr/bin/env python3
"""Converts a PEM CA bundle into a C file with the certificates as a
zlib-compressed concatenation of DER blobs (see src/c/http.c).

usage: mkcabundle.py cacert.pem out.c
"""
import base64
import re
import sys
import zlib


def main():
    src, out = sys.argv[1], sys.argv[2]
    pem = open(src, "r", encoding="utf-8").read()
    blocks = re.findall(
        r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", pem, re.S)
    der = b"".join(base64.b64decode("".join(b.split())) for b in blocks)
    z = zlib.compress(der, 9)
    with open(out, "w") as f:
        f.write("/* generated by tools/mkcabundle.py from %s: %d certificates */\n"
                % (src.rsplit("/", 1)[-1], len(blocks)))
        f.write('#include "picogit.h"\n\n')
        f.write("const size_t pg_cabundle_len = %d;\n" % len(der))
        f.write("const size_t pg_cabundle_z_len = %d;\n" % len(z))
        f.write("const unsigned char pg_cabundle_z[%d] = {" % len(z))
        for i, byte in enumerate(z):
            if i % 20 == 0:
                f.write("\n")
            f.write("%d," % byte)
        f.write("\n};\n")


if __name__ == "__main__":
    main()
